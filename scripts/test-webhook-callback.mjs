//   node scripts/test-webhook-callback.mjs --order-id=<OrderUUID> --result-code=0
//   node scripts/test-webhook-callback.mjs --checkout-id=<CheckoutRequestID> --result-code=1037

import fs from 'fs'
import path from 'path'

const envPath = path.resolve(process.cwd(), '.env.local')
if (fs.existsSync(envPath)) {
  const lines = fs.readFileSync(envPath, 'utf8').split(/\r?\n/)
  for (const line of lines) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eqIdx = trimmed.indexOf('=')
    if (eqIdx > 0) {
      const key = trimmed.slice(0, eqIdx).trim()
      const val = trimmed.slice(eqIdx + 1).trim()
      if (!process.env[key]) process.env[key] = val
    }
  }
}

const supabaseUrl = (process.env.NEXT_PUBLIC_SUPABASE_URL || '').trim()
const anonKey = (process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || '').trim()
const storeId = (
  process.env.NEXT_PUBLIC_STORE_ID || '00000000-0000-0000-0000-000000000001'
).trim()

function normalizeMsisdn(phone) {
  const digits = String(phone || '').replace(/\D/g, '')
  if (digits.startsWith('0') && digits.length === 10) return `254${digits.slice(1)}`
  if (digits.startsWith('254') && digits.length === 12) return digits
  return `254${digits}`
}

async function listRecentOrdersWithStk() {
  const res = await fetch(
    `${supabaseUrl}/rest/v1/orders?store_id=eq.${storeId}&order=created_at.desc&limit=5&select=id,order_number,payment_status,order_status,total_amount,mpesa_checkout_request_id,mpesa_merchant_request_id`,
    {
      headers: {
        apikey: anonKey,
        Authorization: `Bearer ${anonKey}`,
        'x-store-id': storeId,
      },
    }
  )
  const rows = await res.json()
  console.log('\nRecent Orders in Supabase:')
  for (const r of rows || []) {
    console.log(
      `  • Order #${r.order_number} | --order-id=${r.id} | Status: ${r.payment_status} | CheckoutID: ${
        r.mpesa_checkout_request_id || '(NONE - place a new order at /checkout)'
      }`
    )
  }
}

async function main() {
  if (process.env.MPESA_ENV === 'production') {
    console.error('ABORTED: Simulated callbacks are disabled when MPESA_ENV=production.')
    process.exitCode = 1
    return
  }

  const args = Object.fromEntries(
    process.argv.slice(2).map((arg) => {
      const [k, v] = arg.replace(/^--/, '').split('=')
      return [k, v ?? 'true']
    })
  )

  if (args.list === 'true') {
    await listRecentOrdersWithStk()
    return
  }

  const orderIdArg = args['order-id']
  const checkoutIdArg = args['checkout-id']
  const resultCodeArg = args['result-code']
  const targetUrl = args['url'] || 'http://localhost:3000/api/daraja/callback'

  if ((!orderIdArg && !checkoutIdArg) || resultCodeArg === undefined) {
    console.log(
      'Usage:\n  node scripts/test-webhook-callback.mjs --list\n  node scripts/test-webhook-callback.mjs --order-id=<OrderUUID> --result-code=<0|1032|1037>\n  node scripts/test-webhook-callback.mjs --checkout-id=<CheckoutRequestID> --result-code=<0|1032|1037>'
    )
    await listRecentOrdersWithStk()
    process.exitCode = 1
    return
  }

  const resultCode = Number(resultCodeArg)
  if (!Number.isInteger(resultCode) || resultCode < 0) {
    console.error('Invalid --result-code. Use 0 (Success), 1032 (Cancelled), or 1037 (Timeout).')
    process.exitCode = 1
    return
  }

  const filterQuery = orderIdArg
    ? `id=eq.${encodeURIComponent(orderIdArg)}`
    : `mpesa_checkout_request_id=eq.${encodeURIComponent(checkoutIdArg)}`

  const lookupRes = await fetch(
    `${supabaseUrl}/rest/v1/orders?store_id=eq.${storeId}&${filterQuery}&select=id,order_number,customer_phone,total_amount,payment_status,mpesa_checkout_request_id,mpesa_merchant_request_id`,
    {
      headers: {
        apikey: anonKey,
        Authorization: `Bearer ${anonKey}`,
        'x-store-id': storeId,
      },
    }
  )

  const orders = await lookupRes.json()
  if (!Array.isArray(orders) || orders.length !== 1) {
    console.error('\nCould not find a matching order in Supabase for that identifier.')
    console.error(
      'Note: CheckoutRequestIDs generated by test-mpesa-cli.mjs are standalone CLI tests and are not linked to an order in Supabase.'
    )
    await listRecentOrdersWithStk()
    process.exitCode = 1
    return
  }

  const order = orders[0]
  if (!order.mpesa_checkout_request_id || !order.mpesa_merchant_request_id) {
    console.error(
      `\nOrder #${order.order_number} (${order.id}) does not have a CheckoutRequestID saved. Click "Resend M-Pesa Prompt" on http://localhost:3000/orders/${order.id} or place a fresh order at http://localhost:3000/checkout first.`
    )
    await listRecentOrdersWithStk()
    process.exitCode = 1
    return
  }

  const normalizedPhone = normalizeMsisdn(order.customer_phone)
  const simReceipt = `SBX${Date.now().toString().slice(-7)}`

  const payload = {
    Body: {
      stkCallback: {
        MerchantRequestID: order.mpesa_merchant_request_id,
        CheckoutRequestID: order.mpesa_checkout_request_id,
        ResultCode: resultCode,
        ResultDesc:
          resultCode === 0
            ? 'The service request is processed successfully.'
            : resultCode === 1037
            ? 'DS timeout user cannot be reached'
            : 'Request cancelled by user',
        ...(resultCode === 0
          ? {
              CallbackMetadata: {
                Item: [
                  { Name: 'Amount', Value: Number(order.total_amount) },
                  { Name: 'MpesaReceiptNumber', Value: simReceipt },
                  { Name: 'TransactionDate', Value: 20261114193500 },
                  { Name: 'PhoneNumber', Value: normalizedPhone },
                ],
              },
            }
          : {}),
      },
    },
  }

  console.log(`\nSending dev callback for Order #${order.order_number} to ${targetUrl}...`)
  const cbRes = await fetch(targetUrl, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  })

  const cbBody = await cbRes.text()
  console.log(`Callback Endpoint HTTP ${cbRes.status}:`, cbBody)

  if (!cbRes.ok) {
    console.error('Callback endpoint returned a non-2xx HTTP status.')
    process.exitCode = 1
    return
  }

  const verifyRes = await fetch(
    `${supabaseUrl}/rest/v1/orders?id=eq.${order.id}&select=id,order_number,payment_status,order_status,mpesa_receipt_number,mpesa_result_desc`,
    {
      headers: {
        apikey: anonKey,
        Authorization: `Bearer ${anonKey}`,
        'x-store-id': storeId,
      },
    }
  )
  const verifiedRows = await verifyRes.json()
  console.log('\nVerified Post-Callback Order State in Supabase:\n', verifiedRows[0])
}

main().catch((err) => {
  console.error('Simulation error:', err)
  process.exitCode = 1
})